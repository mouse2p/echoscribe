"""``echoscribe report``: render one SVG over everything a workdir holds.

The report is assembled from the files previous stages wrote -- scores,
optionally bench timings and decode rows -- so it can never claim a number
that is not already on disk.  Its metadata stamp deliberately excludes the
work directory's *path*: two runs over identical inputs produce identical
bytes even when they live in different temporary directories, which is what
makes the report itself diffable.

The digest printed on stdout is the same SHA-256 the golden tests over
:mod:`echoscribe.eval.report` use, so "the report changed" is decidable
without opening it, and a regenerated report can be checked against an
archived one with a single string comparison.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from echoscribe.cli.common import EXIT_OK, fail, read_json, read_jsonl
from echoscribe.eval.bench import BenchResult
from echoscribe.eval.edit import align
from echoscribe.eval.report import (
    alignment_section,
    digest_report,
    histogram_section,
    render_report,
    table_section,
    write_report,
)
from echoscribe.meta import run_metadata
from echoscribe.stream.session import read_session


def register(subparsers: argparse._SubParsersAction) -> None:
    """Attach ``report`` to the top-level parser."""
    parser = subparsers.add_parser(
        "report",
        help="render the SVG score report of a scored work directory",
        description=__doc__.split("\n")[0],
    )
    parser.add_argument("--workdir", required=True, help="directory prepared through eval")
    parser.add_argument(
        "--label", default="echoscribe run", help="run label for the metadata stamp"
    )
    parser.add_argument("--out", default="report.svg", help="SVG file to write")
    parser.set_defaults(handler=run)


def run(args: argparse.Namespace) -> int:
    """Assemble, render and write the report; print its digest."""
    root = Path(args.workdir)
    scores_path = root / "scores.json"
    if not scores_path.exists():
        return fail(f"no scores at {scores_path}; run `echoscribe eval` first")
    scores = read_json(scores_path)
    if not isinstance(scores, dict) or "totals" not in scores:
        return fail(f"{scores_path} does not look like an echoscribe score file")
    rows = [
        (str(row["utterance_id"]), f"{row['errors']}/{row['reference_length']}")
        for row in scores["utterances"]
    ]
    sections = [table_section(rows, title=f"scores ({scores['metric']})")]
    bench_path = root / "bench.json"
    if bench_path.exists():
        bench_payload = read_json(bench_path)
        if not isinstance(bench_payload, dict):
            return fail(f"{bench_path} does not look like an echoscribe bench file")
        bench = BenchResult.from_dict(bench_payload)
        sections.append(
            histogram_section(
                bench.samples,
                title="decode seconds per repeat",
                bins=max(1, min(4, len(bench.samples))),
            )
        )
    decode_path = root / "decode.jsonl"
    if decode_path.exists():
        rows_decoded = read_jsonl(decode_path)
        if rows_decoded:
            first = rows_decoded[0]
            sections.append(
                alignment_section(
                    align(list(first["reference_units"]), list(first["hypothesis_units"])).pairs(),
                    title=f"alignment of {first['utterance_id']}",
                )
            )
    session_path = root / "session.jsonl"
    if session_path.exists():
        session = read_session(session_path)
        lengths = [float(record.frames) for record in session.utterances]
        if lengths:
            sections.append(
                histogram_section(
                    lengths,
                    title="utterance length (frames)",
                    bins=max(1, min(4, len(lengths))),
                )
            )
    metadata = run_metadata(
        args.label,
        seed=0,
        level=scores["level"],
        metric=scores["metric"],
        utterances=len(rows),
        errors=scores["totals"]["errors"],
    )
    document = render_report(
        "echoscribe report",
        sections,
        metadata,
        description="generated by `echoscribe report` from files in the work directory",
    )
    target = write_report(root / args.out, document, overwrite=True)
    print(f"echoscribe report: {len(sections)} sections -> {target}")
    print(f"  digest: {digest_report(document)}")
    print("  ground truth: planted transcripts, not human labels of real speech")
    return EXIT_OK
